#!/usr/bin/env python3
# generate-format-registry.py — glob Formats/*/*Parser.swift and emit the registry.
# WHY: compiled Swift cannot importlib a dropped file. The filesystem is still the
# source of truth; this script is the glob. Add a parser = drop a *Parser.swift file
# under Formats/, then rebuild. Do not hand-edit the generated swift.
# NEVER DELETE COMMENTS — explain every non-obvious line.
# Update comments with the code; do not strip them.

from pathlib import Path
import re
import sys

STRUCT_RE = re.compile(r"struct\s+(\w+Parser)\s*:\s*JSONLLineParser")
PARSER_GLOB = "Sources/DBVCore/Parsing/Formats/*/*Parser.swift"
OUT_REL = "Sources/DBVCore/Parsing/DiscoveredFormatParsers/DiscoveredFormatParsers.generated.swift"


def discover_parser_types(root: Path) -> list[str]:
    names: list[str] = []
    for path in sorted(root.glob(PARSER_GLOB)):
        if path.name.startswith("._"):                      # skip macOS resource forks
            continue
        text = path.read_text(encoding="utf-8")
        match = STRUCT_RE.search(text)
        if not match:
            print(f"error: {path} has no `struct …Parser: JSONLLineParser`", file=sys.stderr)
            sys.exit(1)
        names.append(match.group(1))
    return names


def render(names: list[str]) -> str:
    inits = ",\n        ".join(f"{name}()" for name in names) if names else ""
    body = f"[\n        {inits}\n    ]" if names else "[]"
    return (
        "// DiscoveredFormatParsers.generated.swift — DO NOT HAND-EDIT.\n"
        "// Generated by Tools/generate-format-registry.py from Formats/*/*Parser.swift.\n"
        "func discoveredFormatParsers() -> [any JSONLLineParser] {\n"
        f"    {body}\n"
        "}\n"
    )


def main() -> int:
    root = Path(__file__).resolve().parent.parent
    names = discover_parser_types(root)
    out = root / OUT_REL
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(render(names), encoding="utf-8")
    print(f"generate-format-registry: {len(names)} parser(s) -> {out.relative_to(root)}")
    for name in names:
        print(f"  {name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
